import Foundation
import Testing
@testable import CoreTelemetry

@Suite("DisplayMutationGate")
struct DisplayMutationGateTests {
    // Original provider race: the busy flag covered only a posted request, so another
    // control could start during preflight or before the first operation's readback.
    @Test("one operation owns the gate from preflight through readback")
    func operationLeaseSpansRequests() throws {
        var gate = DisplayMutationGate()
        let reservation1 = gate.reserve()
        let owner = try #require(reservation1)
        #expect(gate.owns(owner) && gate.isBusy && !gate.hasUnknownOutcome)
        let assertion2 = (gate.reserve() == nil)
        #expect(assertion2)
        let assertion3 = (gate.posted(requestID: "preflight", lease: owner))
        #expect(assertion3)
        gate.replied(requestID: "preflight")
        let assertion4 = (gate.reserve() == nil)
        #expect(assertion4)
        let assertion5 = (gate.posted(requestID: "mutation", lease: owner))
        #expect(assertion5)
        gate.replied(requestID: "mutation")
        let assertion6 = (gate.reserve() == nil)
        #expect(assertion6)
        let assertion7 = (gate.posted(requestID: "readback", lease: owner))
        #expect(assertion7)
        gate.replied(requestID: "readback")
        #expect(gate.isBusy && gate.owns(owner))
        gate.release(owner)
        #expect(!gate.isBusy && !gate.owns(owner))
        let assertion8 = (gate.reserve() != nil)
        #expect(assertion8)
    }

    @Test("only the current owner may post or release the operation")
    func staleLeasesCannotMutateOwnership() throws {
        var gate = DisplayMutationGate()
        let reservation9 = gate.reserve()
        let old = try #require(reservation9)
        gate.release(old)
        let reservation10 = gate.reserve()
        let current = try #require(reservation10)
        #expect(current != old)
        let assertion11 = (!gate.posted(requestID: "stale", lease: old))
        #expect(assertion11)
        gate.release(old)
        gate.expired(requestID: "stale")
        #expect(gate.owns(current) && gate.isBusy && !gate.hasUnknownOutcome)
        let assertion12 = (gate.posted(requestID: "current", lease: current))
        #expect(assertion12)
        let assertion13 = (!gate.posted(requestID: "current", lease: current))
        #expect(assertion13)
        let assertion14 = (!gate.posted(requestID: "", lease: current))
        #expect(assertion14)
    }

    // Original timeout race: ending the local wait released the UI while BetterDisplay
    // could still be executing the command. Keep the posted operation's outcome unknown.
    @Test("a posted timeout remains blocking after the operation releases")
    func postedTimeoutSurvivesRelease() throws {
        var gate = DisplayMutationGate()
        let reservation15 = gate.reserve()
        let owner = try #require(reservation15)
        let assertion16 = (gate.posted(requestID: "slow", lease: owner))
        #expect(assertion16)
        gate.expired(requestID: "slow")
        gate.release(owner)
        #expect(gate.isBusy && gate.hasUnknownOutcome && !gate.owns(owner))
        let assertion17 = (gate.reserve() == nil)
        #expect(assertion17)
        gate.replied(requestID: "unrelated")
        #expect(gate.isBusy && gate.hasUnknownOutcome)
        gate.replied(requestID: "slow")
        #expect(!gate.isBusy && !gate.hasUnknownOutcome)
        let assertion18 = (gate.reserve() != nil)
        #expect(assertion18)
    }

    @Test("a late response clears its uncertainty while the operation retains its lease")
    func lateResponseDoesNotReleaseTheOwner() throws {
        var gate = DisplayMutationGate()
        let reservation19 = gate.reserve()
        let owner = try #require(reservation19)
        let assertion20 = (gate.posted(requestID: "slow", lease: owner))
        #expect(assertion20)
        gate.expired(requestID: "slow")
        #expect(gate.hasUnknownOutcome)
        let assertion21 = (!gate.posted(requestID: "overlap", lease: owner))
        #expect(assertion21)
        gate.replied(requestID: "slow")
        #expect(!gate.hasUnknownOutcome && gate.isBusy && gate.owns(owner))
        let assertion22 = (gate.reserve() == nil)
        #expect(assertion22)
        let assertion23 = (gate.posted(requestID: "readback", lease: owner))
        #expect(assertion23)
        gate.replied(requestID: "readback")
        gate.release(owner)
        #expect(!gate.isBusy)
    }

    @Test("pre-post cancellation and unrelated responses cannot unlock another request")
    func unrelatedEventsLeaveUnknownRequestBlocking() throws {
        var gate = DisplayMutationGate()
        let reservation24 = gate.reserve()
        let owner = try #require(reservation24)
        let assertion25 = (gate.posted(requestID: "real", lease: owner))
        #expect(assertion25)
        gate.expired(requestID: "real")
        gate.expired(requestID: "cancelled-before-post")
        gate.replied(requestID: "cancelled-before-post")
        gate.release(UUID())
        #expect(gate.hasUnknownOutcome && gate.owns(owner))
        gate.release(owner)
        let assertion26 = (gate.reserve() == nil)
        #expect(assertion26)
        gate.replied(requestID: "real")
        #expect(!gate.isBusy)
    }

    @Test("late cancellation cannot resurrect a completed request or affect the next operation")
    func completedRequestsStayCompleted() throws {
        var gate = DisplayMutationGate()
        let reservation27 = gate.reserve()
        let first = try #require(reservation27)
        let assertion28 = (gate.posted(requestID: "completed", lease: first))
        #expect(assertion28)
        gate.replied(requestID: "completed")
        gate.expired(requestID: "completed")
        #expect(!gate.hasUnknownOutcome)
        gate.release(first)
        let reservation29 = gate.reserve()
        let next = try #require(reservation29)
        let assertion30 = (gate.posted(requestID: "next", lease: next))
        #expect(assertion30)
        gate.expired(requestID: "completed")
        gate.replied(requestID: "completed")
        #expect(!gate.hasUnknownOutcome && gate.owns(next))
        gate.expired(requestID: "next")
        #expect(gate.hasUnknownOutcome)
        gate.replied(requestID: "completed")
        #expect(gate.hasUnknownOutcome)
        gate.replied(requestID: "next")
        gate.expired(requestID: "next")
        #expect(!gate.hasUnknownOutcome && gate.owns(next))
    }

    @Test("an early release cannot allow overlap with an unanswered posted request")
    func outstandingPostsRemainBusy() throws {
        var gate = DisplayMutationGate()
        let reservation31 = gate.reserve()
        let owner = try #require(reservation31)
        let assertion32 = (gate.posted(requestID: "posted", lease: owner))
        #expect(assertion32)
        gate.release(owner)
        #expect(gate.isBusy && !gate.hasUnknownOutcome)
        let assertion33 = (gate.reserve() == nil)
        #expect(assertion33)
        gate.replied(requestID: "another")
        #expect(gate.isBusy)
        gate.replied(requestID: "posted")
        #expect(!gate.isBusy)
    }

    @Test("each timed-out posted request requires its own exact response")
    func multipleUnknownRequestsAreIndependent() throws {
        var gate = DisplayMutationGate()
        let reservation34 = gate.reserve()
        let owner = try #require(reservation34)
        let assertion35 = (gate.posted(requestID: "one", lease: owner))
        #expect(assertion35)
        let assertion36 = (gate.posted(requestID: "two", lease: owner))
        #expect(assertion36)
        gate.expired(requestID: "one")
        gate.expired(requestID: "two")
        gate.release(owner)
        gate.replied(requestID: "one")
        let assertion37 = (gate.hasUnknownOutcome && gate.reserve() == nil)
        #expect(assertion37)
        gate.replied(requestID: "two")
        #expect(!gate.isBusy && !gate.hasUnknownOutcome)
    }
}
