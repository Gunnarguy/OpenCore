-- Migration 4 — saved conversations.
--
-- Chat was ephemeral. Turns lived in a SwiftUI @State array, the model's own Transcript held
-- the continuity, and closing the tab destroyed both. A question worth asking once is usually
-- worth returning to, and there was no way back.
--
-- WHY THIS IS NOT A DERIVED LAYER. A conversation is *primary* data: the user's questions are
-- authored input and nothing in the object graph can reconstruct them. So these tables are
-- deliberately absent from `Store.derivedTables`, and `opencore rebuild` must leave them
-- alone. Putting them there would make `rebuild` destroy the only copy of something, which is
-- the project's first non-negotiable.
--
-- Turn text is stored as written. The answer is *not* re-derivable either: it came from a
-- model whose output is not reproducible, so re-running the question later is a different
-- answer to the same words. That is exactly why the receipt is worth keeping beside it.

CREATE TABLE IF NOT EXISTS conversation (
    id         TEXT PRIMARY KEY,
    -- Taken from the first question rather than generated by a model. A title is a label, and
    -- spending a model call on one would make opening a chat depend on model availability.
    title      TEXT NOT NULL,
    started_at REAL NOT NULL,
    -- Moves on every appended turn, so "recent" means recently *used* rather than recently
    -- created. Sorting a resume list by creation date buries the thread you were just in.
    updated_at REAL NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_conversation_updated ON conversation(updated_at DESC);

CREATE TABLE IF NOT EXISTS conversation_turn (
    id              TEXT PRIMARY KEY,
    conversation_id TEXT NOT NULL REFERENCES conversation(id) ON DELETE CASCADE,
    -- Explicit rather than inferred from a timestamp. Two turns can land inside the same
    -- millisecond, and an answer arriving before its question would be unreadable.
    ordinal         INTEGER NOT NULL,
    role            TEXT NOT NULL,
    text            TEXT NOT NULL,
    -- JSON. Denormalised on purpose: these are what the answer was *actually shown* against,
    -- and an object edited or re-ingested later must not silently rewrite the history of an
    -- answer that was given before the edit. A receipt that changes retroactively is not a
    -- receipt.
    sources         TEXT NOT NULL,
    verdicts        TEXT NOT NULL,
    -- The receipt row proper, so `opencore trace` reaches a saved chat turn. NULL is a real
    -- state: an errored turn never produced one, and writing a hollow receipt to avoid a NULL
    -- is the "plausible default" this project refuses everywhere else.
    receipt_id      TEXT REFERENCES receipt(id) ON DELETE SET NULL,
    model           TEXT,
    error           TEXT,
    created_at      REAL NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_turn_conversation ON conversation_turn(conversation_id, ordinal);
